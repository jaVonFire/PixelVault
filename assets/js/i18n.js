function currentLang() {
  var l = localStorage.getItem('pv_lang') || 'es';
  return (I18N[l]) ? l : 'es';
}
function setLang(l) {
  if (!I18N[l]) l = 'es';
  localStorage.setItem('pv_lang', l);
  document.documentElement.setAttribute('lang', l);
  applyTranslations();
}
/* Devuelve el texto traducido. Soporta reemplazos {clave}. */
function t(key, params) {
  var dict = I18N[currentLang()];
  var str = dict[key] !== undefined ? dict[key] : (I18N.es[key] || key);
  if (params) {
    Object.keys(params).forEach(function (k) {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k]);
    });
  }
  return str;
}

/* Aplica traducciones a todos los elementos con data-i18n */
function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  if (typeof updateAuthUI === 'function') updateAuthUI();
}
